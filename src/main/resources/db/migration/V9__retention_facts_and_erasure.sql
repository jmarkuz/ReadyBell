-- Data retention (see docs/DATA_RETENTION_PLAN.md): facts without personal data, the means to forget the personal data.

-- Every status change of an order, appended in the transaction that changes it (time to prepare, peaks, hand-over)
CREATE TABLE order_status_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id uuid NOT NULL,
    tenant_id uuid NOT NULL,
    from_status varchar(32),
    to_status varchar(32) NOT NULL,
    at timestamp(6) with time zone NOT NULL
);
CREATE INDEX idx_order_status_history_order ON order_status_history (order_id, at);
CREATE INDEX idx_order_status_history_tenant_at ON order_status_history (tenant_id, at);

-- One row per finished order, without customer name, items by name or any link to a person. It outlives the order row's
-- personal data: this is what analytics reads. approximate = timings estimated (written for an order that predates the table)
CREATE TABLE order_fact (
    order_id uuid PRIMARY KEY,
    tenant_id uuid NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    in_progress_at timestamp(6) with time zone,
    ready_at timestamp(6) with time zone,
    finished_at timestamp(6) with time zone NOT NULL,
    outcome varchar(16) NOT NULL,
    item_count integer NOT NULL,
    quantity integer NOT NULL,
    connected boolean NOT NULL,
    approximate boolean NOT NULL DEFAULT false
);
CREATE INDEX idx_order_fact_tenant_created ON order_fact (tenant_id, created_at);

-- Set when the personal data of a finished order was removed (customer name, items, link to the session)
ALTER TABLE "order" ADD COLUMN anonymized_at timestamp(6) with time zone;
CREATE INDEX idx_order_retention ON "order" (updated_at)
    WHERE anonymized_at IS NULL AND status IN ('COMPLETED', 'CANCELLED');

-- What each retention run did, for the operator (no personal data)
CREATE TABLE retention_run (
    id uuid PRIMARY KEY,
    task varchar(64) NOT NULL,
    started_at timestamp(6) with time zone NOT NULL,
    finished_at timestamp(6) with time zone,
    affected integer NOT NULL DEFAULT 0,
    dry_run boolean NOT NULL DEFAULT false,
    error varchar(255)
);

-- Proof that an erasure was carried out, without the personal data: the subject is a keyed hash. After a restore from a
-- backup the log is replayed so that what was forgotten stays forgotten
CREATE TABLE erasure_log (
    id uuid PRIMARY KEY,
    tenant_id uuid NOT NULL,
    subject_type varchar(32) NOT NULL,
    subject_ref varchar(128) NOT NULL,
    scope varchar(64) NOT NULL,
    performed_at timestamp(6) with time zone NOT NULL,
    performed_by varchar(32) NOT NULL
);
CREATE INDEX idx_erasure_log_tenant ON erasure_log (tenant_id, performed_at);

-- When and under which notice the customer agreed to the push ("Notify me")
ALTER TABLE device_subscription
    ADD COLUMN consent_at timestamp(6) with time zone,
    ADD COLUMN consent_notice varchar(32);
